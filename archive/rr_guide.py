def render_rr_guide(compact: bool = True) -> None:
    """מצייר את המדריך. compact=True מקטין ריווח ומתאים לתוך expander."""
    pad = ".45rem .7rem" if compact else ".7rem .9rem"
    fs = ".86rem" if compact else ".92rem"

    blocks = []
    for title, color, items in SECTIONS:
        rows = ""
        for term, what, how in items:
            rows += f'''
      <tr style="border-top:1px solid #ffffff14;">
        <td style="padding:{pad};font-weight:700;white-space:nowrap;
                   vertical-align:top;border-right:3px solid {color};">
          {_esc(term)}</td>
        <td style="padding:{pad};vertical-align:top;opacity:.85;">{_esc(what)}</td>
        <td style="padding:{pad};vertical-align:top;line-height:1.6;">{_esc(how)}</td>
      </tr>'''
        blocks.append(f'''
  <div style="font-weight:800;color:{color};margin:.9rem 0 .25rem;text-align:right;">{_esc(title)}</div>
  <table style="width:100%;border-collapse:collapse;font-size:{fs};color:{_TEXT};">
    <thead><tr style="background:#ffffff0a;">
      <th style="padding:{pad};text-align:right;width:18%;">מונח</th>
      <th style="padding:{pad};text-align:right;width:30%;">מה זה</th>
      <th style="padding:{pad};text-align:right;">איך לקרוא את זה</th>
    </tr></thead>
    <tbody>{rows}</tbody>
  </table>''')

    principles = "".join(
        f'<li style="margin-bottom:.3rem;">{_esc(p)}</li>' for p in _PRINCIPLES)

    st.markdown(f'''
<div dir="rtl" style="overflow-x:auto;color:{_TEXT};text-align:right;">
{"".join(blocks)}
  <div style="font-weight:800;color:{_AMBER};margin:1.1rem 0 .25rem;text-align:right;">
    ארבעה כללים שלא כדאי לעקוף</div>
  <ul style="font-size:{fs};line-height:1.65;padding-right:1.1rem;padding-left:0;margin:.2rem 0 .4rem;text-align:right;direction:rtl;list-style-position:inside;">
    {principles}
  </ul>
</div>''', unsafe_allow_html=True)


