_FIELDS = [
    ("what", "מה זה", "var(--c-text-1, #c9d1d9)"),
    ("how", "איך מחושב", "var(--c-text-1, #c9d1d9)"),
    ("moves", "מה מזיז אותו", "var(--c-text-1, #c9d1d9)"),
    ("use", "מה עושים עם זה", "var(--c-green, #16c784)"),
    ("trap", "המלכודת", "var(--c-red, #ea3943)"),
]


def _topic_html(topic: dict) -> str:
    rows = []
    for key, label, color in _FIELDS:
        rows.append(
            f'<div style="margin:.45rem 0;">'
            f'<span style="color:{color};font-weight:700;font-size:.82rem;">'
            f'{label}</span>'
            f'<div style="font-size:.9rem;line-height:1.65;opacity:.9;">'
            f'{topic[key]}</div></div>')
    return f'<div dir="rtl">{"".join(rows)}</div>'


def render_strategy_guide(compact: bool = False) -> None:
    """compact=True מקטין כותרות, לשימוש בתוך אקורדיון בטאב האסטרטגיה."""
    heading = "h4" if compact else "h3"
    st.markdown(
        f'<div dir="rtl"><{heading} style="margin:.2rem 0;">'
        f'מדריך — הציון המשולב</{heading}>'
        f'<div style="opacity:.72;font-size:.87rem;line-height:1.6;">'
        f'כל פרמטר במנוע, מה הוא מודד ואיפה הוא משקר. '
        f'המלכודות הן החלק החשוב: רובן היו באגים אמיתיים באפליקציה הזו.'
        f'</div></div>', unsafe_allow_html=True)

    current_tag = None
    for topic in TOPICS:
        if topic["tag"] != current_tag:
            current_tag = topic["tag"]
            st.markdown(
                f'<div dir="rtl" style="margin:.9rem 0 .2rem;font-size:.75rem;'
                f'letter-spacing:.08em;opacity:.55;font-weight:700;">'
                f'{current_tag}</div>', unsafe_allow_html=True)
        st.markdown(
            f'<div dir="rtl" style="border-right:2px solid var(--c-blue-lt,#4d9fff);'
            f'padding:.5rem .8rem;margin:.5rem 0;background:#ffffff08;'
            f'border-radius:0 8px 8px 0;">'
            f'<div style="font-weight:700;font-size:.95rem;margin-bottom:.3rem;">'
            f'{topic["title"]}</div>'
            f'{_topic_html(topic)}</div>', unsafe_allow_html=True)


